/// Formats the latest body-weight measurement for the AI user context.
///
/// The stored value stays in kilograms; only the presentation follows the
/// user's preferred [system].
String formatLatestWeightSummary(
  BodyMeasurement measurement,
  UnitSystem system,
) {
  final weight = formatWeight(
    measurement.bodyWeight,
    system,
    suffix: system.suffix,
  );
  final date = measurement.date;
  return 'Latest weight: $weight recorded on ${date.month}/${date.day}/${date.year}.';
}

class ProposedExerciseItem {
  final String name;
  final int sets;
  final int reps;
  final double load;
  final int restTime;

  ProposedExerciseItem({
    required this.name,
    this.sets = 3,
    this.reps = 10,
    this.load = 0.0,
    this.restTime = 90,
  });

  factory ProposedExerciseItem.fromJson(Map<String, dynamic> json) {
    return ProposedExerciseItem(
      name: (json['name'] ?? json['exercise'] ?? json['title'] ?? 'Exercise')
          .toString(),
      sets: (json['sets'] as num?)?.toInt() ?? 3,
      reps: (json['reps'] as num?)?.toInt() ?? 10,
      load:
          (json['load'] as num?)?.toDouble() ??
          (json['weight'] as num?)?.toDouble() ??
          0.0,
      restTime: (json['restTime'] as num?)?.toInt() ?? 90,
    );
  }
}

class ProposedRoutine {
  final String title;
  final String notes;
  final List<ProposedExerciseItem> exercises;

  ProposedRoutine({
    required this.title,
    required this.notes,
    required this.exercises,
  });

  factory ProposedRoutine.fromJson(Map<String, dynamic> json) {
    final list = (json['exercises'] as List? ?? json['workout'] as List? ?? []);
    return ProposedRoutine(
      title: (json['title'] ?? json['name'] ?? '').toString(),
      notes:
          (json['notes'] ??
                  json['description'] ??
                  'Generated by AI Workout Assistant')
              .toString(),
      exercises: list
          .map((e) => ProposedExerciseItem.fromJson(e as Map<String, dynamic>))
          .toList(),
    );
  }
}

