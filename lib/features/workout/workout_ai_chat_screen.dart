class _WorkoutAiChatScreenState extends ConsumerState<WorkoutAiChatScreen> {
  final TextEditingController _textController = TextEditingController();
  final ScrollController _scrollController = ScrollController();
  final List<Map<String, String>> _messages = [
    {
      'role': 'model',
      'content':
          'Hi! I am your AI Workout Assistant. Tell me what kind of workout routine or guidance you need today, and I will tailor it based on your fitness preferences and history.',
    },
  ];
  bool _isLoading = false;
  final Set<int> _savedProposalMessageIndices = {};

  @override
  void dispose() {
    _textController.dispose();
    _scrollController.dispose();
    super.dispose();
  }

  void _scrollToBottom() {
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (_scrollController.hasClients) {
        _scrollController.animateTo(
          _scrollController.position.maxScrollExtent,
          duration: const Duration(milliseconds: 300),
          curve: Curves.easeOut,
        );
      }
    });
  }

  ProposedRoutine? _parseProposal(String content) {
    // 1. Try parsing json code blocks: ```json ... ```
    final jsonBlockRegExp = RegExp(
      r'```(?:json)?\s*([\s\S]*?)\s*```',
      caseSensitive: false,
    );
    for (final match in jsonBlockRegExp.allMatches(content)) {
      final code = match.group(1)?.trim();
      if (code != null && code.startsWith('{') && code.endsWith('}')) {
        try {
          final decoded = json.decode(code);
          if (decoded is Map<String, dynamic> &&
              (decoded.containsKey('exercises') ||
                  decoded.containsKey('workout'))) {
            final proposal = ProposedRoutine.fromJson(decoded);
            if (proposal.exercises.isNotEmpty) {
              return proposal;
            }
          }
        } catch (_) {}
      }
    }

    // 2. Fallback heuristic parser: match Markdown headings and bullet items
    // e.g. "### Routine: Chest & Triceps" or "Routine: Full Body"
    final routineTitleRegExp = RegExp(
      r'(?:###?\s*Routine:?|Routine:\s*)([^\n]+)',
      caseSensitive: false,
    );
    final titleMatch = routineTitleRegExp.firstMatch(content);

    // Match exercise bullet lines: e.g. "- Bench Press: 3 sets x 10 reps" or "• Squat - 4 sets of 8 reps"
    final exerciseLineRegExp = RegExp(
      r'^(?:[-*•]|\d+\.)\s+([A-Za-z0-9\s\-_]+?)(?::|\s+-|\s+–)\s*(\d+)\s*sets?(?:\s*(?:x|of|\*)\s*(\d+)(?:-\d+)?\s*reps?)?',
      caseSensitive: false,
      multiLine: true,
    );

    final exerciseMatches = exerciseLineRegExp.allMatches(content).toList();
    if (exerciseMatches.length >= 2) {
      final title = titleMatch != null
          ? titleMatch.group(1)!.trim()
          : 'AI Tailored Routine';
      final exercises = exerciseMatches.map((m) {
        final name = m.group(1)!.trim();
        final sets = int.tryParse(m.group(2) ?? '3') ?? 3;
        final reps = int.tryParse(m.group(3) ?? '10') ?? 10;
        return ProposedExerciseItem(name: name, sets: sets, reps: reps);
      }).toList();

      return ProposedRoutine(
        title: title,
        notes: 'AI generated routine proposal',
        exercises: exercises,
      );
    }

    return null;
  }

  Future<void> _saveRoutineToDb(
    ProposedRoutine proposal,
    int messageIndex,
  ) async {
    final datasetRepo = ref.read(datasetRepositoryProvider);
    final workoutRepo = ref.read(workoutRepositoryProvider);

    try {
      final allExercises = await datasetRepo.getExercises();
      final now = DateTime.now();

      final exercisesWithSets = <ExerciseWithSets>[];

      for (int i = 0; i < proposal.exercises.length; i++) {
        final item = proposal.exercises[i];
        final cleanName = item.name.toLowerCase().replaceAll(
          RegExp(r'[^a-z0-9]'),
          '',
        );

        // Match existing exercise or fallback
        ExerciseDataDC? matchedDC;
        for (final ex in allExercises) {
          final dbClean = ex.name.toLowerCase().replaceAll(
            RegExp(r'[^a-z0-9]'),
            '',
          );
          if (dbClean == cleanName ||
              dbClean.contains(cleanName) ||
              cleanName.contains(dbClean)) {
            matchedDC = ex;
            break;
          }
        }

        matchedDC ??= (allExercises.isNotEmpty
            ? allExercises.first
            : ExerciseDataDC(
                id: 'custom_${item.name.toLowerCase().replaceAll(' ', '_')}',
                name: item.name,
                level: Level.BEGINNER,
                primaryMuscles: const [Muscle.CHEST],
                secondaryMuscles: const [],
                instructions: const [
                  'Perform repetitions safely with good form.',
                ],
                category: Category.STRENGTH,
                images: const [],
                isCustomExercise: true,
              ));

        final exerciseId = DateTime.now().millisecondsSinceEpoch + i;
        final exercise = Exercise(
          id: exerciseId,
          exerciseDataId: matchedDC.id,
          notes: '',
          setMode: defaultSetModeForExercise(matchedDC),
          restTime: item.restTime > 0 ? item.restTime : 90,
          position: i,
          workoutId: 0,
        );

        final sets = List.generate(
          item.sets > 0 ? item.sets : 3,
          (sIndex) => WorkoutSet(
            id: DateTime.now().millisecondsSinceEpoch + (i * 100) + sIndex + 1,
            load: item.load,
            weightUnit: WeightUnit.kg,
            reps: item.reps > 0 ? item.reps : 10,
            elapsedTime: 0,
            completed: false,
            setType: SetType.NORMAL,
            exerciseId: exerciseId,
          ),
        );

        exercisesWithSets.add(
          ExerciseWithSets(
            exercise: exercise,
            exerciseDC: matchedDC,
            sets: sets,
          ),
        );
      }

      final workout = Workout(
        id: 0,
        routineId: 0,
        notes: proposal.notes,
        title: proposal.title,
        state: WorkoutState.ROUTINE,
        timeElapsed: 0,
        position: 0,
        created: now,
        completed: now,
        isTemporal: false,
      );

      final newWorkoutId = await workoutRepo.addWorkoutWithExercisesAndSets(
        WorkoutWithExercisesAndSets(
          workout: workout,
          exercisesWithSets: exercisesWithSets,
        ),
      );

      if (!mounted) return;

      setState(() {
        _savedProposalMessageIndices.add(messageIndex);
      });

      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('Routine "${proposal.title}" saved to your routines!'),
          action: SnackBarAction(
            label: 'View',
            onPressed: () {
              Navigator.pushNamed(
                context,
                '/info-workout',
                arguments: newWorkoutId,
              );
            },
          ),
        ),
      );
    } catch (e) {
      if (!mounted) return;
      ScaffoldMessenger.of(
        context,
      ).showSnackBar(SnackBar(content: Text('Failed to save routine: $e')));
    }
  }

  Future<void> _sendMessage() async {
    final text = _textController.text.trim();
    if (text.isEmpty || _isLoading) return;

    _textController.clear();
    setState(() {
      _messages.add({'role': 'user', 'content': text});
      _isLoading = true;
    });
    _scrollToBottom();

    final settings = ref.read(settingsProvider);
    final repo = ref.read(workoutRepositoryProvider);

    // 1. Workout history summary
    String? workoutSummary;
    if (settings.aiAllowWorkoutHistory) {
      try {
        final allCompleted = await repo
            .watchWorkoutsWithExercisesAndSetsByState(WorkoutState.COMPLETED)
            .first;
        if (allCompleted.isNotEmpty) {
          final recent = allCompleted
              .take(3)
              .map((w) {
                final exNames = w.exercisesWithSets
                    .map((e) => e.exerciseDC.name)
                    .take(4)
                    .join(', ');
                return '${w.workout.title} (${w.exercisesWithSets.length} exercises: $exNames)';
              })
              .join('; ');
          workoutSummary =
              '${allCompleted.length} total completed workouts. Recent sessions: $recent.';
        }
      } catch (_) {}
    }

    // 2. Meal history summary
    String? mealSummary;
    if (settings.aiAllowMealHistory) {
      try {
        final mealPlans = await ref
            .read(mealRepositoryProvider)
            .getMealPlansWithMealsAndItemsByState(MealPlanState.LOGGED)
            .first;
        if (mealPlans.isNotEmpty) {
          final recentPlan = mealPlans.first;
          final totalFoods = recentPlan.meals.fold(
            0,
            (sum, m) => sum + m.items.length,
          );
          mealSummary =
              '${mealPlans.length} logged meal days. Most recent log: "${recentPlan.mealPlan.title}" with $totalFoods items consumed.';
        }
      } catch (_) {}
    }

    // 3. User stats & progress summary
    String? statsSummary;
    if (settings.aiAllowUserStats) {
      try {
        final allCompleted = await repo
            .watchWorkoutsWithExercisesAndSetsByState(WorkoutState.COMPLETED)
            .first;
        if (allCompleted.isNotEmpty) {
          final totalVolume = allCompleted.fold<double>(
            0.0,
            (sum, w) => sum + WorkoutStatsHelper.calculateWorkoutTonnage(w),
          );
          final avgDuration =
              (allCompleted.fold<int>(
                        0,
                        (sum, w) => sum + w.workout.timeElapsed,
                      ) /
                      allCompleted.length /
                      60)
                  .round();
          statsSummary =
              'Completed: ${allCompleted.length} workouts. Total volume: ${totalVolume.toStringAsFixed(0)} kg. Average workout duration: $avgDuration mins.';
        } else {
          statsSummary =
              'User is just starting out. 0 workouts completed so far.';
        }
      } catch (_) {}
    }

    // 4. Last user measurements
    String? measurementsSummary;
    if (settings.aiAllowMeasurements) {
      try {
        final measurementRepo = ref.read(measurementRepositoryProvider);
        final measurements = await measurementRepo.getAllMeasurements().first;
        final advancedMeasurements = await measurementRepo
            .getAllAdvancedBodyMeasurements()
            .first;
        final parts = <String>[];
        if (measurements.isNotEmpty) {
          final last = measurements.first;
          parts.add(
            'Latest weight: ${last.bodyWeight} kg recorded on ${last.date.month}/${last.date.day}/${last.date.year}.',
          );
        }
        if (advancedMeasurements.isNotEmpty) {
          final lastAdvanced = advancedMeasurements.first;
          if (lastAdvanced.bodyFatPercentage != null) {
            parts.add('Body fat: ${lastAdvanced.bodyFatPercentage}%.');
          }
          if (lastAdvanced.muscleMassPercentage != null) {
            parts.add('Muscle mass: ${lastAdvanced.muscleMassPercentage}%.');
          }
        }
        if (parts.isNotEmpty) {
          measurementsSummary = parts.join(' ');
        }
      } catch (_) {}
    }

    final contextPrompt = AIService.assembleWorkoutAiPrompt(
      aiWorkoutGenerationEnabled: settings.aiWorkoutGenerationEnabled,
      aiAllowUserPreferences: settings.aiAllowUserPreferences,
      userPreferences: settings.userPreferences,
      aiAllowWorkoutHistory: settings.aiAllowWorkoutHistory,
      workoutHistorySummary: workoutSummary,
      aiAllowMealHistory: settings.aiAllowMealHistory,
      mealHistorySummary: mealSummary,
      aiAllowUserStats: settings.aiAllowUserStats,
      statisticsSummary: statsSummary,
      aiAllowMeasurements: settings.aiAllowMeasurements,
      measurementsSummary: measurementsSummary,
    );

    // 5. Compact exercise catalog so the model prefers real DB exercises.
    var exerciseCatalog = <String>[];
    if (settings.aiWorkoutGenerationEnabled &&
        settings.aiToken.trim().isNotEmpty) {
      try {
        final exercises = await ref
            .read(datasetRepositoryProvider)
            .getExercises();
        exerciseCatalog = exercises
            .map((exercise) => exercise.name.trim())
            .where((name) => name.isNotEmpty)
            .take(AIService.maxWorkoutCatalogNames)
            .toList();
      } catch (_) {}
    }

    final historyForApi = _messages.sublist(0, _messages.length - 1);

    final response = await AIService.chatWithWorkoutAssistant(
      provider: settings.aiProvider,
      apiKey: settings.aiToken,
      model: settings.aiModel,
      userContext: contextPrompt,
      conversationHistory: historyForApi,
      userMessage: text,
      exerciseCatalog: exerciseCatalog,
    );

    if (!mounted) return;

    setState(() {
      _messages.add({'role': 'model', 'content': response});
      _isLoading = false;
    });
    _scrollToBottom();
  }

